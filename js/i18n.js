/* ============================================================
   College Tycoon — translations

   Every player-visible string lives here under a key. Nothing else
   in the codebase holds display text, so adding a language means
   adding one block to DICT and one entry to LANGS.

   t("key", {a: 1}) looks the key up in the active language and
   substitutes {a} placeholders. Missing keys fall back to English,
   then to the key itself, so a gap shows up as an obvious token
   rather than a blank.

   News entries and end-of-run text are stored as {k, p} rather than
   finished strings, so switching language re-renders the whole
   history rather than leaving a bilingual log behind.
   ============================================================ */

const LANGS = [
  { id: "en", label: "EN", name: "English" },
  { id: "zh", label: "中文", name: "简体中文" },
];

const LANG_KEY = "college-tycoon-lang";

let CURRENT_LANG = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && LANGS.some((l) => l.id === saved)) return saved;
  } catch (err) { /* storage unavailable; fall through */ }
  /* Chinese browsers get Chinese by default, everyone else English. */
  const nav = (navigator.language || "en").toLowerCase();
  return nav.startsWith("zh") ? "zh" : "en";
})();

function getLang() { return CURRENT_LANG; }

const MONTHS_ZH = ["1月", "2月", "3月", "4月", "5月", "6月",
                   "7月", "8月", "9月", "10月", "11月", "12月"];

/** Month name in the active language. */
function monthName(i) {
  return CURRENT_LANG === "zh" ? MONTHS_ZH[i] : MONTH_NAMES[i];
}

function setLang(id) {
  if (!LANGS.some((l) => l.id === id)) return;
  CURRENT_LANG = id;
  try { localStorage.setItem(LANG_KEY, id); } catch (err) { /* ignore */ }
  document.documentElement.lang = id === "zh" ? "zh-CN" : "en";
}

/** Translate a key, substituting {placeholders} from params. */
function t(key, params) {
  const table = DICT[CURRENT_LANG] || DICT.en;
  let s = table[key];
  if (s === undefined) s = DICT.en[key];
  if (s === undefined) return key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, name) =>
    params[name] === undefined ? m : params[name]);
}

/** Render a stored {k, p} message. Plain strings pass straight through. */
function tr(msg) {
  if (!msg) return "";
  if (typeof msg === "string") return msg;
  return t(msg.k, msg.p);
}

/** Build a stored message. Events and the engine return these. */
function m(k, p) { return p ? { k, p } : { k }; }

